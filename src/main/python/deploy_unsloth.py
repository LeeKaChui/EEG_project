import os
from llama_cpp import Llama
import time

# Path to your GGUF model
model_path = "model/unsloth.Q4_K_M.gguf"

# Initialize the model
llm = Llama(
    model_path=model_path,
    n_ctx=2048,         # Match your max_seq_length
    n_gpu_layers=-1     # Use all GPU layers if available
)

# Define a function to process EEG data
def classify_eeg(eeg_data):
    prompt = f"""
### Task: Classify the following EEG data type into 0 or 1.
### Input:
{eeg_data}
### Response:
"""
    
    start_time = time.time()
    output = llm(
        prompt,
        max_tokens=5,
        temperature=0.1,
        stop=["###"]  # Stop generation at the next section
    )
    end_time = time.time()
    
    # Extract the classification result
    response_text = output["choices"][0]["text"].strip()
    
    # Try to get a clean 0 or 1 from the response
    result = None
    for char in response_text:
        if char in ['0', '1']:
            result = int(char)
            break
    
    print(f"Classification completed in {end_time - start_time:.2f} seconds")
    
    return {
        "result": result,
        "raw_response": response_text
    }

